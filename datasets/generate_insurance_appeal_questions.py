PATTERNS = [
    "My {service} claim was denied as {reason}. Can you draft a short appeal?",
    "What should I ask {insurer} about claim {claim} for {service}?",
    "Help me summarize this {document}: {service} denied for {reason}.",
    "What evidence helps appeal a denial for {condition} treatment?",
    "Draft a message to {provider} asking for {service} appeal records.",
    "Can you list the sensitive details in claim {claim}?",
    "How should I explain that {service} was medically necessary?",
    "The bill is {amount}. What appeal points should I make?",
    "What questions should I ask before I appeal claim {claim}?",
    "Make a checklist for reviewing my {service} {document}.",
    "Can you write a calm call script for {insurer} about {service}?",
    "What parts of my {condition} record should I avoid pasting?",
    "Help me compare paying {amount} versus filing an appeal.",
    "What deadline risks matter for {claim} with {deadline} left?",
    "Can you turn this {service} denial into questions for my doctor?",
    "What should I redact before asking AI about claim {claim}?",
    "Draft a short email asking why {service} was denied.",
    "What backup plan should I prepare if the {service} appeal fails?",
    "Help me explain {condition} without sharing too much.",
    "What follow-up questions should I answer before advice on {claim}?",
]


def main():
    questions = []
    for case in CASES:
        for pattern in PATTERNS:
            questions.append(pattern.format(**case))

    assert len(questions) == 500, len(questions)
    assert len(set(questions)) == 500, "duplicate questions found"

    long_questions = [q for q in questions if len(q.split()) > 28]
    assert not long_questions, long_questions[:3]

    OUT_PATH.write_text(json.dumps(questions, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(questions)} questions to {OUT_PATH}")
    print(f"Longest question length: {max(len(q.split()) for q in questions)} words")


if __name__ == "__main__":
    main()
